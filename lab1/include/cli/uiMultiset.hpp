#ifndef UIMULTISET_HPP

#define UIMULTISET_HPP
#include "storageMultiset.hpp"
#include <limits>
#include <stack>

/**
 * @brief Пользовательский интерфейс для работы с мультимножествами.
 *
 * Позволяет создавать, удалять и просматривать мультимножества,
 * вычислять выражения с операциями над ними и сохранять результаты.
 */
class UIMultiset
{
private:
    storageMultiset storage;

    /**
     * @brief Создаёт мультимножество и добавляет его в хранилище.
     *
     * Если указатель равен nullptr, пользователь вводит элементы
     * мультимножества. В противном случае сохраняется переданное
     * мультимножество.
     */
    void createMultiset(const multiset *);

    /**
     * @brief Удаляет мультимножество из хранилища по введённому имени.
     */
    void destructMultiset();

    /**
     * @brief Выводит сохранённые мультимножества и их имена.
     */
    void viewMultiset();

    /**
     * @brief Организует ввод, вычисление и сохранение результата выражения.
     */
    void performOperation();

    /**
     * @brief Возвращает приоритет арифметического оператора.
     *
     * Оператор '*' имеет приоритет 2, '+' — 1, '-' — 0.
     * Для остальных символов возвращается -1.
     */
    int getPriorityOperation(const char &) const;

    /**
     * @brief Преобразует выражение из инфиксной формы в постфиксную.
     *
     * Использует стек операторов и учитывает приоритеты операций
     * и круглые скобки. Имена мультимножеств в выходном выражении
     * разделяются символом '_'.
     * @return true после завершения обработки выражения.
     */
    bool parser(const std::string &, std::string &) const;

    /**
     * @brief Вычисляет постфиксное выражение над мультимножествами.
     *
     * Использует стек операндов и выполняет операции '+', '*' и '-'.
     * Имена мультимножеств извлекаются из хранилища.
     * @return true, если вычисление завершено и в стеке остался
     * ровно один результат; иначе false.
     */
    bool solver(const std::string &, multiset &);

    /**
     * @brief Предлагает сохранить результат вычисления.
     *
     * При подтверждении передаёт результат в метод создания
     * мультимножества.
     */
    void saver(const multiset &);

public:
    /**
     * @brief Запускает главное меню работы с мультимножествами.
     *
     * Предоставляет операции создания, удаления и просмотра
     * мультимножеств, вычисления выражений и выхода из программы.
     */
    void menu();
};

#endif